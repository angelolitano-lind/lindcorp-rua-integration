CREATE TABLE LND_0005_CFG_PARAM (
    INTERFACE_ID        VARCHAR2(20) DEFAULT 'LND_0005' NOT NULL,
    PARAM_KEY           VARCHAR2(50) NOT NULL,
    PARAM_VALUE         VARCHAR2(255) NOT NULL,
    DESCRIPTION         VARCHAR2(255),
    CREATED_AT          DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_LND_0005_CFG_PARAM PRIMARY KEY (INTERFACE_ID, PARAM_KEY)
);

CREATE TABLE LND_0005_CFG_CONNECTION (
    ENVIRONMENT_CODE     VARCHAR2(10) NOT NULL,
    CONNECTION_CODE      VARCHAR2(50) NOT NULL,
    CONNECTION_TYPE      VARCHAR2(20) DEFAULT 'REST_API' NOT NULL,
    FLOW_DIRECTION       VARCHAR2(10) DEFAULT 'OUTBOUND' NOT NULL,
    DESCRIPTION          VARCHAR2(255),
    BASE_URL             VARCHAR2(500) NOT NULL,
    HTTP_METHOD          VARCHAR2(10) DEFAULT 'PUT' NOT NULL,
    CONTENT_TYPE         VARCHAR2(50) DEFAULT 'application/json' NOT NULL,
    CREDENTIAL_TYPE      VARCHAR2(20) DEFAULT 'APEX_WEB' NOT NULL,
    CREDENTIAL_STATIC_ID VARCHAR2(100) NOT NULL,
    APEX_WORKSPACE       VARCHAR2(100) NOT NULL,
    TIMEOUT_SECONDS      NUMBER DEFAULT 60 NOT NULL,
    ACTIVE_IND           VARCHAR2(1) DEFAULT 'Y' NOT NULL,
    CREATED_AT           DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_LND_0005_CFG_CONN PRIMARY KEY (ENVIRONMENT_CODE, CONNECTION_CODE)
);

CREATE TABLE LND_0005_CTL_EXEC (
    EXEC_ID             NUMBER GENERATED ALWAYS AS IDENTITY,
    JOB_NAME            VARCHAR2(100) NOT NULL,
    START_TIME          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    END_TIME            TIMESTAMP WITH TIME ZONE,
    STATUS              VARCHAR2(20) DEFAULT 'RUNNING' NOT NULL,
    RECORDS_READ        NUMBER DEFAULT 0,
    RECORDS_SUCCESS     NUMBER DEFAULT 0,
    RECORDS_FAILED      NUMBER DEFAULT 0,
    ERROR_MESSAGE       VARCHAR2(4000),
    CONSTRAINT PK_LND_0005_CTL_EXEC PRIMARY KEY (EXEC_ID)
);

CREATE TABLE LND_0005_OBX_PO_RECEIPTS (
    OUTBOX_ID           NUMBER GENERATED ALWAYS AS IDENTITY,
    BUSINESS_KEY        VARCHAR2(100) NOT NULL,
    PAYLOAD_JSON        CLOB NOT NULL,
    PROCESS_STATUS      VARCHAR2(1) DEFAULT 'U' NOT NULL,
    ATTEMPT_COUNT       NUMBER DEFAULT 0 NOT NULL,
    MAX_ATTEMPTS        NUMBER DEFAULT 5 NOT NULL,
    NEXT_ATTEMPT_AT     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    LAST_ERROR_CODE     VARCHAR2(100),
    LAST_ERROR_MSG      VARCHAR2(4000),
    CREATED_AT          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_LND_0005_OBX_POR PRIMARY KEY (OUTBOX_ID),
    CONSTRAINT UK_LND_0005_OBX_POR_BK UNIQUE (BUSINESS_KEY)
);

CREATE INDEX IX_LND_0005_OBX_PROC ON LND_0005_OBX_PO_RECEIPTS (PROCESS_STATUS, NEXT_ATTEMPT_AT, CREATED_AT);

CREATE TABLE LND_0005_LOG_DISPATCH (
    LOG_ID              NUMBER GENERATED ALWAYS AS IDENTITY,
    OUTBOX_ID           NUMBER NOT NULL,
    HTTP_STATUS_CODE    NUMBER,
    EXECUTION_TIME_MS   NUMBER,
    REQUEST_PAYLOAD     CLOB,
    RESPONSE_PAYLOAD    CLOB,
    ERROR_STACK         VARCHAR2(4000),
    CREATED_AT          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_LND_0005_LOG_DISP PRIMARY KEY (LOG_ID)
);